/// Repository interface and implementation for transit operations.
abstract class TransitRepository {
  /// True while bus locations are generated by the local route simulator.
  bool get usesSimulatedTelemetry;

  Future<List<BusRoute>> getRoutes();
  Future<List<Stop>> getStops();
  Future<List<RouteStopOccurrence>> getRouteStops(String routeId);
  Future<List<Bus>> getActiveBuses();
  Future<List<ScheduledDeparture>> getScheduledDepartures();
  Stream<List<Bus>> watchActiveBuses();
  Future<Stop?> getNearestStop(GeoPoint userLocation);
  Future<Bus?> getBusById(String busId);
}

class SupabaseTransitRepository implements TransitRepository {
  SupabaseTransitRepository(this._supabase);

  final SupabaseClient? _supabase;
  StreamController<List<Bus>>? _busStreamController;
  Timer? _simulationTimer;
  List<Bus> _currentBuses = _defaultNitcBuses;
  final Map<String, double> _distanceAlongRoute = {'bus-1': 78, 'bus-2': 42};

  @override
  bool get usesSimulatedTelemetry => false;

  @override
  Future<List<BusRoute>> getRoutes() async {
    if (_supabase != null) {
      final stops = await getStops();
      final stopMap = {for (final s in stops) s.id: s};

      // Query routes table
      final response = await _supabase
          .from('routes')
          .select()
          .eq('is_active', true)
          .order('route_code', ascending: true);

      final rawRoutes = response as List;
      if (rawRoutes.isEmpty) return const [];

      // Query all route stops in sequence
      List<RouteStopOccurrence> allOccurrences = [];
      try {
        final rsResponse = await _supabase
            .from('route_stops')
            .select(
              'route_id, stop_id, sequence, distance_from_start, estimated_duration_sec',
            )
            .order('sequence', ascending: true);
        allOccurrences = (rsResponse as List).map((rawRow) {
          final row = rawRow as Map<String, dynamic>;
          final stopId = row['stop_id']?.toString() ?? '';
          final resolvedStop = stopMap[stopId];
          return RouteStopOccurrence.fromJson(row, stop: resolvedStop);
        }).toList();
      } catch (rsError) {
        AppLogger.warning('Failed to fetch route_stops: $rsError');
      }

      final routes = rawRoutes.map((row) {
        final map = row as Map<String, dynamic>;
        final routeId = (map['id'] ?? '').toString();
        final occurrences =
            allOccurrences.where((o) => o.routeId == routeId).toList()
              ..sort((a, b) => a.sequence.compareTo(b.sequence));

        return BusRoute.fromJson(
          map,
          stops: stops,
          stopOccurrences: occurrences,
        );
      }).toList();

      return routes;
    }
    return _defaultNitcRoutes;
  }

  @override
  Future<List<Stop>> getStops() async {
    if (_supabase != null) {
      final response = await _supabase
          .from('stops')
          .select()
          .eq('is_active', true)
          .order('name', ascending: true);
      return (response as List)
          .map((e) => Stop.fromJson(e as Map<String, dynamic>))
          .where((stop) => stop.isActive)
          .toList();
    }
    return _defaultNitcStops;
  }

  @override
  Future<List<RouteStopOccurrence>> getRouteStops(String routeId) async {
    if (_supabase != null) {
      final stops = await getStops();
      final stopMap = {for (final s in stops) s.id: s};

      final response = await _supabase
          .from('route_stops')
          .select(
            'route_id, stop_id, sequence, distance_from_start, estimated_duration_sec',
          )
          .eq('route_id', routeId)
          .order('sequence', ascending: true);

      return (response as List).map((rawRow) {
        final row = rawRow as Map<String, dynamic>;
        final stopId = row['stop_id']?.toString() ?? '';
        return RouteStopOccurrence.fromJson(row, stop: stopMap[stopId]);
      }).toList();
    }

    final matchedRoute = _defaultNitcRoutes
        .where((r) => r.id == routeId)
        .firstOrNull;
    return matchedRoute?.stopOccurrences ?? const [];
  }

  @override
  Future<List<ScheduledDeparture>> getScheduledDepartures() async {
    if (_supabase == null) return const [];

    try {
      final response = await _supabase.from('bus_timings').select();
      return (response as List)
          .map(
            (row) => ScheduledDeparture.fromJson(row as Map<String, dynamic>),
          )
          .toList();
    } catch (e) {
      AppLogger.warning('Failed to fetch scheduled bus departures: $e');
      return const [];
    }
  }

  @override
  Future<List<Bus>> getActiveBuses() async {
    if (_supabase != null) {
      try {
        final response = await _supabase.from('buses').select();
        final buses = (response as List)
            .map((e) => Bus.fromJson(e as Map<String, dynamic>))
            .toList();
        if (buses.isNotEmpty) return buses;
      } catch (e) {
        AppLogger.warning(
          'Failed to fetch buses from Supabase, falling back to local data: $e',
        );
      }
    }
    return _currentBuses;
  }

  @override
  Stream<List<Bus>> watchActiveBuses() {
    _busStreamController ??= StreamController<List<Bus>>.broadcast(
      onListen: () {
        _busStreamController?.add(_currentBuses);
        _startSimulationTimer();
      },
      onCancel: () {
        if (!(_busStreamController?.hasListener ?? false)) {
          _simulationTimer?.cancel();
        }
      },
    );

    return _busStreamController!.stream;
  }

  void _startSimulationTimer() {
    _simulationTimer?.cancel();
    if (_currentBuses.isEmpty) return;
    _simulationTimer = Timer.periodic(const Duration(seconds: 3), (timer) {
      if (!(_busStreamController?.hasListener ?? false)) {
        timer.cancel();
        return;
      }

      final now = DateTime.now();
      _currentBuses = _currentBuses.map((bus) {
        if (!bus.isLive || bus.routeId == null) return bus;

        final route = _defaultNitcRoutes
            .where((item) => item.id == bus.routeId)
            .firstOrNull;
        if (route == null || route.path.length < 2) return bus;

        final distanceMoved = bus.position.speedKmH * 1000 * 3 / 3600;
        final distanceAlongRoute =
            (_distanceAlongRoute[bus.id] ?? 0) + distanceMoved;
        _distanceAlongRoute[bus.id] = distanceAlongRoute;

        return bus.copyWith(
          lastUpdated: now,
          position: _positionAlongRoute(
            route,
            distanceAlongRoute,
            bus.position,
            now,
          ),
        );
      }).toList();

      _busStreamController?.add(_currentBuses);
    });
  }

  @override
  Future<Stop?> getNearestStop(GeoPoint userLocation) async {
    final stops = await getStops();
    if (stops.isEmpty) return null;

    Stop? nearest;
    var minDistance = double.infinity;

    for (final stop in stops) {
      final dist = userLocation.distanceToMeters(stop.location);
      if (dist < minDistance) {
        minDistance = dist;
        nearest = stop;
      }
    }

    return nearest;
  }

  @override
  Future<Bus?> getBusById(String busId) async {
    final buses = await getActiveBuses();
    try {
      return buses.firstWhere((b) => b.id == busId);
    } catch (_) {
      return null;
    }
  }
}

BusPosition _positionAlongRoute(
  BusRoute route,
  double distanceAlongRoute,
  BusPosition previous,
  DateTime timestamp,
) {
  final path = route.path;
  final segmentLengths = <double>[];
  var totalLength = 0.0;
  for (var index = 0; index < path.length - 1; index++) {
    final length = path[index].distanceToMeters(path[index + 1]);
    segmentLengths.add(length);
    totalLength += length;
  }
  if (totalLength <= 0) return previous;

  var remaining = distanceAlongRoute % totalLength;
  for (var index = 0; index < segmentLengths.length; index++) {
    final segmentLength = segmentLengths[index];
    if (remaining <= segmentLength || index == segmentLengths.length - 1) {
      final start = path[index];
      final end = path[index + 1];
      final progress = (remaining / segmentLength).clamp(0.0, 1.0).toDouble();
      return BusPosition(
        point: GeoPoint(
          latitude: start.latitude + (end.latitude - start.latitude) * progress,
          longitude:
              start.longitude + (end.longitude - start.longitude) * progress,
        ),
        heading: start.bearingTo(end),
        speedKmH: previous.speedKmH,
        accuracyMeters: 4.1,
        sequenceNumber: previous.sequenceNumber + 1,
        timestamp: timestamp,
      );
    }
    remaining -= segmentLength;
  }

  return previous;
}

final transitRepositoryProvider = Provider<TransitRepository>((ref) {
  final supabase = ref.watch(supabaseClientProvider);
  return SupabaseTransitRepository(supabase);
});

